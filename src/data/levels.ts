export function levelById(id: string): LevelDef {
  return LEVELS.find((l) => l.id === id) ?? LEVELS[0];
}

export function parseMap(raw: string): string[] {
  return raw
    .trim()
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0);
}
